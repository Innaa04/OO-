using System;

namespace Rozumatic_OOP_Pract5
{
    // Модернізований клас Point
    public class Point
    {
        public double X;
        public double Y;

        // 1. Конструктор без параметрів (ініціалізує точку в нулі)
        public Point()
        {
            X = 0;
            Y = 0;
        }

        // 2. Конструктор з параметрами (приймає початкові значення координат)
        public Point(double x, double y)
        {
            X = x;
            Y = y;
        }

        // 3. ДОМАШНЄ ЗАВДАННЯ: Конструктор копіювання
        // Приймає як параметр інший об'єкт цього ж класу та копіює його дані
        public Point(Point other)
        {
            if (other != null)
            {
                X = other.X;
                Y = other.Y;
            }
        }

        // Метод для виведення координат на екран
        public void DisplayInfo(string pointName)
        {
            Console.WriteLine($"📍 Точка {pointName}: ({X}; {Y})");
        }
    }

    class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("==========================================================================");
            Console.WriteLine("     ПРАКТИЧНЕ ЗАНЯТТЯ №5: ПЕРЕВАНТАЖЕННЯ КОНСТРУКТОРІВ КЛАСУ            ");
            Console.WriteLine("==========================================================================");

            // Тестування створення об'єктів трьома способами:

            // Спосіб 1: Виклик конструктора без параметрів (Загальне завдання)
            Point p1 = new Point();
            Console.WriteLine("\n1. Створення через конструктор без параметрів:");
            p1.DisplayInfo("A");

            // Спосіб 2: Виклик конструктора з параметрами (Загальне завдання)
            Point p2 = new Point(4.5, -2.8);
            Console.WriteLine("\n2. Створення через конструктор з параметрами:");
            p2.DisplayInfo("B");

            // Спосіб 3: Виклик конструктора копіювання (Домашнє завдання)
            // Створюємо нову точку C, яка буде повною копією точки B
            Point p3 = new Point(p2);
            Console.WriteLine("\n3. Створення через конструктор копіювання (копія точки B):");
            p3.DisplayInfo("C");

            Console.WriteLine("--------------------------------------------------------------------------");
            Console.WriteLine("✅ Практичну роботу №5 успішно виконано!");
        }
    }
}
